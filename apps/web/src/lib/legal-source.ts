/**
 * Builds the published legal pages from `docs/legal` (the single source the lawyers edit):
 * fills the `{{placeholders}}` with `docs/legal/empresa.json`. Used by `scripts/build-legal.ts`
 * and by the test that keeps `src/content/legal.generated.ts` in sync. Node only.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

export const LEGAL_DOCUMENTS = [
  { slug: 'terminos', file: 'terminos-y-condiciones.md' },
  { slug: 'privacidad', file: 'politica-de-privacidad.md' },
  { slug: 'cancelacion-y-reembolsos', file: 'politica-de-cancelacion-y-reembolsos.md' },
  { slug: 'condiciones-para-empresas', file: 'condiciones-para-empresas.md' },
  { slug: 'cookies', file: 'politica-de-cookies.md' },
] as const;

export interface LegalSource {
  version: string;
  reviewed: boolean;
  documents: { slug: string; title: string; markdown: string }[];
}

export function readLegalSource(root: string): LegalSource {
  const dir = join(root, 'docs', 'legal');
  const data = JSON.parse(readFileSync(join(dir, 'empresa.json'), 'utf8')) as Record<
    string,
    string | boolean
  >;
  const fill = (text: string) =>
    text.replace(/\{\{(\w+)\}\}/g, (match, key: string) => {
      const value = data[key];
      if (typeof value !== 'string') throw new Error(`Unknown legal placeholder ${match}`);
      return value;
    });
  return {
    version: String(data.version),
    reviewed: data.revisado_por_abogado === true,
    documents: LEGAL_DOCUMENTS.map(({ slug, file }) => {
      const markdown = fill(readFileSync(join(dir, file), 'utf8')).trim();
      const title = /^# (.+)$/m.exec(markdown)?.[1] ?? slug;
      // The title is rendered by the page; the body starts after it.
      return { slug, title, markdown: markdown.replace(/^# .+\n+/, '') };
    }),
  };
}

export function renderLegalModule(source: LegalSource): string {
  return `// Generated by \`pnpm --filter @vtp/web legal:build\` from docs/legal. Do not edit.\n\nexport const LEGAL = ${JSON.stringify(source, null, 2)} as const;\n`;
}
